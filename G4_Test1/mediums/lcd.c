// pines compartidos con el RGB (jumpers J2/J3/J4), se reconfiguran antes de usar la LCD.
// SCE esta a GND: un pulso falso en SCLK desfasa los bits de la LCD hasta el reset,
// por eso SCLK nunca se deja flotando (pull-down y MODER en una sola escritura)
static void lcd_pins(void){
    GPIOB->AFR[0] = (GPIOB->AFR[0] & ~((0xFU << (3*4)) | (0xFU << (5*4)))) | (5U << (3*4)) | (5U << (5*4));
    GPIOB->MODER  = (GPIOB->MODER & ~((3U << (3*2)) | (3U << (5*2)))) | (2U << (3*2)) | (2U << (5*2));

    GPIOA->MODER  = (GPIOA->MODER & ~((3U << (8*2)) | (3U << (11*2)))) | (1U << (8*2)) | (1U << (11*2));
    LUZ_ON();
}

static void spi_send(uint8_t b){
    while(!(SPI1->SR & SPI_SR_TXE)){}
    *(volatile uint8_t *)&SPI1->DR = b;
}

// esperar a que salga el ultimo byte antes de mover D/C
static void spi_wait(void){
    while(SPI1->SR & SPI_SR_FTLVL){}
    while(SPI1->SR & SPI_SR_BSY){}
}

static void lcd_cmd(uint8_t c){
    spi_wait();
    DC_CMD();
    spi_send(c);
    spi_wait();
}

static void lcd_data(uint8_t d){
    DC_DATA();
    spi_send(d);
}

void lcd_config(void){
    RCC->AHB2ENR |= RCC_AHB2ENR_GPIOAEN | RCC_AHB2ENR_GPIOBEN;
    RCC->APB2ENR |= RCC_APB2ENR_SPI1EN;

    GPIOB->PUPDR = (GPIOB->PUPDR & ~(3U << (3*2))) | (2U << (3*2));

    // maestro, solo transmite (1 linea), modo 0, 16 MHz / 8 = 2 MHz
    // se habilita antes de pasarle los pines para que SCLK quede manejado en bajo
    SPI1->CR1 = SPI_CR1_BIDIMODE | SPI_CR1_BIDIOE | SPI_CR1_MSTR | SPI_CR1_SSM | SPI_CR1_SSI | (2U << SPI_CR1_BR_Pos);
    SPI1->CR2 = (7U << SPI_CR2_DS_Pos) | SPI_CR2_FRXTH;
    SPI1->CR1 |= SPI_CR1_SPE;

    lcd_pins();
    for(volatile uint32_t k = 0; k < 2000; k++){}

    lcd_cmd(0x21);   // instrucciones extendidas
    lcd_cmd(0xB8);   // contraste
    lcd_cmd(0x04);   // coef. temperatura
    lcd_cmd(0x14);   // bias
    lcd_cmd(0x20);   // instrucciones basicas
    lcd_cmd(0x0C);   // modo normal
    lcd_clear();
}

void lcd_goto(uint8_t x, uint8_t fila){
    lcd_pins();
    lcd_cmd(0x80 | x);
    lcd_cmd(0x40 | fila);
}

void lcd_clear(void){
    lcd_goto(0, 0);
    for(int k = 0; k < 504; k++){
        lcd_data(0x00);
    }
    lcd_goto(0, 0);
}

void lcd_putc(char c){
    if(c < 0x20 || c > 0x7F){
        c = ' ';
    }
    for(int k = 0; k < 5; k++){
        lcd_data(font[c - 0x20][k]);
    }
    lcd_data(0x00);
}

// columna k (0-4) del caracter c, para dibujar texto en un buffer
uint8_t lcd_font_col(char c, int k){
    if(c < 0x20 || c > 0x7F){
        c = ' ';
    }
    return font[c - 0x20][k];
}

// manda una pantalla completa (84 x 48 = 504 bytes, 6 bancos de 8 pixeles)
void lcd_send_buffer(const uint8_t *buf){
    lcd_goto(0, 0);
    for(int k = 0; k < 504; k++){
        lcd_data(buf[k]);
    }
    spi_wait();
}

// 14 caracteres por fila, la LCD salta sola a la siguiente fila
void lcd_print(char *s){
    lcd_clear();
    while(*s){
        lcd_putc(*s);
        s++;
    }
    spi_wait();
}
